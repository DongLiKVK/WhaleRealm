#!/usr/bin/env bash
# Cloudflare 回源段同步脚本（whalerealm.top 生产机）
# 作用：把 Cloudflare 官方 IPv4/IPv6 段写进 nginx 的两个 snippet：
#   1) cloudflare-realip.conf —— 让 access.log / Express 拿到真实访客 IP
#   2) cloudflare-allow.conf  —— 只允许 Cloudflare 回源，其余直接 403
#
# 用法：
#   ./cf-nginx-sync.sh                 # 只打印将要写入的内容（dry-run，默认）
#   sudo ./cf-nginx-sync.sh --apply    # 写入 snippet 并 nginx -t + reload
#   sudo ./cf-nginx-sync.sh --realip-only --apply   # 只做真实 IP，不加白名单
#
# 注意：--apply 之前必须确认 Cloudflare 已经 Active（NS 已切换、橙云已开），
#       否则会把直连流量全部挡掉。脚本在 apply 前会探测本机 443 是否已带 CF 头。
set -euo pipefail

MODE="dry-run"
REALIP_ONLY=0
for arg in "$@"; do
  case "$arg" in
    --apply) MODE="apply" ;;
    --realip-only) REALIP_ONLY=1 ;;
    -h|--help) sed -n '2,20p' "$0"; exit 0 ;;
    *) echo "未知参数: $arg" >&2; exit 2 ;;
  esac
done

REALIP=/etc/nginx/snippets/cloudflare-realip.conf
ALLOW=/etc/nginx/snippets/cloudflare-allow.conf
TMPDIR=$(mktemp -d)
trap 'rm -rf "$TMPDIR"' EXIT

fetch_ranges() {
  curl -fsS --max-time 15 https://www.cloudflare.com/ips-v4
  curl -fsS --max-time 15 https://www.cloudflare.com/ips-v6
}

echo "== 拉取 Cloudflare 官方回源段 =="
fetch_ranges > "$TMPDIR/ranges.txt"
V4=$(grep -c '\.' "$TMPDIR/ranges.txt" || true)
V6=$(grep -c ':' "$TMPDIR/ranges.txt" || true)
echo "IPv4 段: $V4  IPv6 段: $V6"

{
  echo "# generated by cf-nginx-sync.sh at $(date -u +%FT%TZ)"
  while read -r ip; do
    [ -n "$ip" ] && echo "set_real_ip_from $ip;"
  done < "$TMPDIR/ranges.txt"
  echo "real_ip_header CF-Connecting-IP;"
  echo "real_ip_recursive on;"
} > "$TMPDIR/realip.conf"

{
  echo "# generated by cf-nginx-sync.sh at $(date -u +%FT%TZ)"
  while read -r ip; do
    [ -n "$ip" ] && echo "allow $ip;"
  done < "$TMPDIR/ranges.txt"
  echo "deny all;"
} > "$TMPDIR/allow.conf"

echo
echo "== cloudflare-realip.conf =="
cat "$TMPDIR/realip.conf"
if [ "$REALIP_ONLY" -eq 0 ]; then
  echo
  echo "== cloudflare-allow.conf（前 8 行）=="
  head -8 "$TMPDIR/allow.conf"
  echo "... 共 $(wc -l < "$TMPDIR/allow.conf") 行"
fi

if [ "$MODE" != "apply" ]; then
  echo
  echo "dry-run 结束。确认无误后执行：sudo $0 --apply"
  exit 0
fi

echo
echo "== 探测本机是否已经走 Cloudflare =="
if command -v curl >/dev/null 2>&1; then
  HDR=$(curl -sSI --max-time 10 https://whalerealm.top/ 2>/dev/null || true)
  if echo "$HDR" | grep -qi '^cf-ray:'; then
    echo "检测到 cf-ray，Cloudflare 已接管，可以继续。"
  else
    echo "未检测到 cf-ray：Cloudflare 可能还没生效。" >&2
    echo "继续 apply 会让直连用户全部 403。已中止。" >&2
    exit 3
  fi
fi

install -m 644 "$TMPDIR/realip.conf" "$REALIP"
echo "写入 $REALIP"
if [ "$REALIP_ONLY" -eq 0 ]; then
  install -m 644 "$TMPDIR/allow.conf" "$ALLOW"
  echo "写入 $ALLOW"
fi

nginx -t
systemctl reload nginx
echo "nginx 已 reload。验证：curl -sI https://whalerealm.top/ | grep -i cf-ray"
